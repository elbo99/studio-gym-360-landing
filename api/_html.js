// Security audit fix (2026-09-18): free-text booking fields were
// interpolated straight into HTML emails sent from a verified domain —
// escape before ever putting user input in an email body.
function escapeHtml(value) {
  if (value === null || value === undefined) return '';
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

module.exports = { escapeHtml };
